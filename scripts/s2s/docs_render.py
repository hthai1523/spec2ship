"""Render generated Markdown views: spec.md, RTM, delivery report.

Canonical data lives in JSON; these are views. spec.md sections the generator
cannot derive from requirements are left as explicit TODO markers for Claude /
the developer instead of being invented.
"""
from __future__ import annotations

import os

from typing import Any

from .common import now_iso

OUT_OF_SCOPE = {"deferred", "rejected"}


def _src(r: dict[str, Any]) -> str:
    s = r["source"]
    bits = [s["document"]]
    if "page" in s:
        bits.append(f"p.{s['page']}")
    if s.get("section"):
        bits.append(f"§{s['section']}")
    if "line" in s:
        bits.append(f"L{s['line']}")
    return ", ".join(bits)


def render_spec(reqs: dict[str, Any], project: str, extra: dict[str, str] | None = None) -> str:
    extra = extra or {}
    rs = reqs["requirements"]
    in_scope = [r for r in rs if r["status"] not in OUT_OF_SCOPE]
    out_scope = [r for r in rs if r["status"] in OUT_OF_SCOPE]

    def by_type(*types: str) -> list[dict[str, Any]]:
        return [r for r in in_scope if r["type"] in types]

    def req_lines(items: list[dict[str, Any]]) -> list[str]:
        if not items:
            return ["_None identified._"]
        out = []
        for r in items:
            flag = " _(inferred)_" if r.get("origin") == "inferred" else ""
            out.append(f"- **{r['id']}** {r['title']} [{r['priority']}]{flag} — {r['description']} _(source: {_src(r)})_")
        return out

    def section(title: str, body: list[str]) -> list[str]:
        return [f"## {title}", ""] + body + [""]

    L = [f"# Specification — {project}", "", f"_Generated by Spec2Ship on {now_iso()} from requirements.json. "
         "Requirement IDs are stable; edit requirements.json and regenerate rather than editing IDs here._", ""]
    L += section("Overview", [extra.get("overview", "<!-- TODO(spec2ship): one-paragraph product overview confirmed by the developer -->")])
    L += section("Scope", [f"- In scope: {len(in_scope)} requirement(s)", f"- Out of scope (deferred/rejected): {len(out_scope)}"])
    L += section("Functional Requirements", req_lines(by_type("functional")))
    rules = [f"- {r['id']}: {rule}" for r in in_scope for rule in r.get("business_rules", [])]
    L += section("Business Rules", rules or ["_None identified._"])
    L += section("Non-functional Requirements", req_lines(by_type("non_functional", "security", "constraint")))
    L += section("UI / Design Requirements", req_lines(by_type("ui") + [r for r in in_scope if r["type"] != "ui" and "frontend" in r.get("layers", [])]))
    L += section("API Requirements", req_lines(by_type("api") + [r for r in in_scope if r["type"] != "api" and "api" in r.get("layers", [])]))
    L += section("Data Requirements", req_lines(by_type("data") + [r for r in in_scope if r["type"] != "data" and "database" in r.get("layers", [])]))
    acs = []
    for r in in_scope:
        for ac in r["acceptance_criteria"]:
            acs.append(f"- **{ac['id']}** ({r['id']}) Given {ac['given']}, when {ac['when']}, then {ac['then']}.")
    L += section("Acceptance Criteria", acs or ["_None derivable; see Open Questions._"])
    L += section("Dependencies", [extra.get("dependencies", "<!-- TODO(spec2ship): external systems, services and packages -->")])
    assumptions = [f"- {r['id']}: {a}" for r in in_scope for a in r.get("assumptions", [])]
    L += section("Assumptions", assumptions or ["_None recorded._"])
    qs = []
    for r in rs:
        for q in r.get("ambiguities", []):
            state = f"resolved: {q['resolution']}" if q.get("resolution") else ("**BLOCKING**" if q["blocking"] else "open")
            qs.append(f"- {q['id']} ({r['id']}, {q.get('kind', 'ambiguity')}, {state}): {q['question']}")
    L += section("Open Questions", qs or ["_None._"])
    L += section("Out of Scope", [f"- {r['id']} {r['title']} ({r['status']})" for r in out_scope] or ["_Nothing explicitly excluded._"])
    L += section("Completion Criteria", [
        "- Every in-scope requirement is `implemented` and each of its acceptance criteria has PASS evidence (see verification.json).",
        "- Criteria checked only by LLM review are reported as REVIEWED, not PASS.",
        "- Project-native lint/typecheck/test/build commands pass or are reported with their real status.",
    ])
    return "\n".join(L)


