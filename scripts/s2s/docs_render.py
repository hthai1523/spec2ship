def build_rtm(reqs: dict[str, Any], mapping: dict[str, Any] | None, tasks: dict[str, Any] | None,
              task_map: dict[str, str] | None, statuses: dict[str, str] | None, verification: dict[str, Any] | None,
              changed_files: dict[str, list[str]] | None = None) -> dict[str, Any]:
    from .harness_adapter import is_done

    task_map = task_map or {}
    statuses = statuses or {}
    figma_by_req: dict[str, list[dict[str, Any]]] = {}
    for m in (mapping or {}).get("mappings", []):
        figma_by_req.setdefault(m["requirement_id"], []).append(
            {"node_id": m["node_id"], "node_name": m.get("node_name"), "relation": m["relation"], "confidence": m["confidence"]})
    tasks_by_req: dict[str, list[dict[str, Any]]] = {}
    orphan_tasks = []
    for ph in (tasks or {}).get("phases", []):
        for t in ph["tasks"]:
            hid = task_map.get(t["id"])
            status = statuses.get(hid, "not_handed_off" if not hid else "missing")
            entry = {"task_id": t["id"], "harness_task_id": hid, "status": status, "files": t.get("files", [])}
            for rid in t["requirement_ids"]:
                tasks_by_req.setdefault(rid, []).append(entry)
            if not t["requirement_ids"]:
                orphan_tasks.append({**entry, "reason": t.get("no_requirement_reason")})
    ev_by_ac: dict[str, dict[str, Any]] = {}
    for res in (verification or {}).get("results", []):
        ev_by_ac[res["criterion_id"]] = res  # last record wins
    rows = []
    for r in reqs["requirements"]:
        ts = tasks_by_req.get(r["id"], [])
        acs = []
        for ac in r["acceptance_criteria"]:
            ev = ev_by_ac.get(ac["id"])
            acs.append({"criterion_id": ac["id"], "status": ev["status"] if ev else "NOT_RUN",
                        "method": ev["method"] if ev else None, "evidence": (ev or {}).get("evidence")})
        if r["status"] in OUT_OF_SCOPE:
            derived = r["status"]
        elif any(t["status"].startswith("blocked") for t in ts):
            derived = "blocked"
        elif ts and all(is_done(t["status"]) for t in ts):
            derived = "verified" if acs and all(a["status"] == "PASS" for a in acs) else "implemented"
        elif any(t["status"] not in ("cc:TODO", "not_handed_off", "missing") for t in ts):
            derived = "in_progress"
        elif ts and all(t["harness_task_id"] for t in ts):
            derived = "approved"
        elif figma_by_req.get(r["id"]) or ts:
            derived = "mapped"
        else:
            derived = r["status"]
        rows.append({
            "requirement_id": r["id"], "title": r["title"], "priority": r["priority"], "declared_status": r["status"],
            "derived_status": derived, "figma": figma_by_req.get(r["id"], []), "tasks": ts,
            "code_evidence": (changed_files or {}).get(r["id"], []), "acceptance": acs,
        })
    in_scope = [x for x in rows if x["declared_status"] not in OUT_OF_SCOPE]
    all_acs = [a for x in in_scope for a in x["acceptance"]]
    metrics = {
        "requirements_total": len(rows),
        "requirements_in_scope": len(in_scope),
        "mapped_to_design": sum(1 for x in in_scope if x["figma"]),
        "mapped_to_tasks": sum(1 for x in in_scope if x["tasks"]),
        "with_code_evidence": sum(1 for x in in_scope if x["code_evidence"]),
        "covered_by_tests": sum(1 for x in in_scope if any(a["method"] in ("unit-test", "integration-test", "e2e-test") for a in x["acceptance"])),
        "criteria_total": len(all_acs),
        "criteria_pass": sum(1 for a in all_acs if a["status"] == "PASS"),
        "criteria_reviewed_only": sum(1 for a in all_acs if a["status"] == "REVIEWED"),
        "criteria_fail": sum(1 for a in all_acs if a["status"] == "FAIL"),
        "criteria_not_run": sum(1 for a in all_acs if a["status"] == "NOT_RUN"),
        "implemented": sum(1 for x in in_scope if x["derived_status"] in ("implemented", "verified")),
        "verified": sum(1 for x in in_scope if x["derived_status"] == "verified"),
        "blocked": sum(1 for x in in_scope if x["derived_status"] == "blocked"),
        "deferred_or_rejected": len(rows) - len(in_scope),
        "unmapped_to_tasks": [x["requirement_id"] for x in in_scope if not x["tasks"]],
        "orphan_tasks": [t["task_id"] for t in orphan_tasks],
    }
    return {"schema_version": "1.0", "generated_at": now_iso(), "rows": rows, "orphan_tasks": orphan_tasks, "metrics": metrics}


def render_rtm_md(rtm: dict[str, Any]) -> str:
    m = rtm["metrics"]
    L = ["# Requirement Traceability Matrix", "", f"_Generated {rtm['generated_at']} from rtm.json (canonical)._", "",
         "## Metrics", "", "| Metric | Value |", "|---|---|"]
    for k in ("requirements_in_scope", "mapped_to_design", "mapped_to_tasks", "with_code_evidence", "covered_by_tests",
              "criteria_total", "criteria_pass", "criteria_reviewed_only", "criteria_fail", "criteria_not_run",
              "implemented", "verified", "blocked", "deferred_or_rejected"):
        L.append(f"| {k.replace('_', ' ')} | {m[k]} |")
    L.append(f"| unmapped to tasks | {', '.join(m['unmapped_to_tasks']) or '-'} |")
    L.append(f"| orphan tasks | {', '.join(m['orphan_tasks']) or '-'} |")
    L += ["", "## Matrix", "", "| Requirement | Status | Figma nodes | Tasks (Harness) | Acceptance |", "|---|---|---|---|---|"]
    for x in rtm["rows"]:
        fig = ", ".join(f"{f['node_id']} ({f['confidence']})" for f in x["figma"]) or "-"
        ts = ", ".join(f"{t['task_id']}→{t['harness_task_id'] or '?'} {t['status']}" for t in x["tasks"]) or "-"
        acs = ", ".join(f"{a['criterion_id']}: {a['status']}" for a in x["acceptance"]) or "-"
        L.append(f"| {x['requirement_id']} {x['title']} | {x['derived_status']} | {fig} | {ts} | {acs} |")
    return "\n".join(L) + "\n"


def render_report(project: str, st: dict[str, Any], rtm: dict[str, Any], verification: dict[str, Any] | None,
                  project_root: str | None = None) -> str:
    m = rtm["metrics"]
    groups: dict[str, list[dict[str, Any]]] = {}
    for x in rtm["rows"]:
        groups.setdefault(x["derived_status"], []).append(x)

    def grp(title: str, keys: tuple[str, ...]) -> list[str]:
        items = [x for k in keys for x in groups.get(k, [])]
        body = [f"- {x['requirement_id']} {x['title']}" for x in items] or ["_None._"]
        return [f"### {title} ({len(items)})", ""] + body + [""]

    L = [f"# Delivery Report — {project}", "", f"- Run: `{st['run_id']}`", f"- Workflow state: **{st['state']}**",
         f"- Generated: {now_iso()}", ""]
    appr = st.get("approval")
    L.append(f"- Plan approval: {'approved by ' + appr['approver'] + ' at ' + appr['approved_at'] + ' (plan ' + appr['plan_hash'][:12] + ')' if appr else '**not approved**'}")
    h = st.get("harness") or {}
    ledger = h.get("plans_path")
    if ledger and project_root:  # the report may be committed or shared: no machine-specific paths
        try:
            ledger = os.path.relpath(ledger, project_root).replace("\\", "/")
        except ValueError:  # different drive on Windows
            pass
    L.append(f"- Harness ledger: {ledger or 'not handed off'}")
    L += ["", "## Requirement status", ""]
    L += grp("Verified (all acceptance criteria PASS with evidence)", ("verified",))
    L += grp("Implemented, not fully verified", ("implemented",))
    L += grp("In progress", ("in_progress",))
    L += grp("Not started (approved / mapped / analyzed)", ("approved", "mapped", "analyzed", "extracted"))
    L += grp("Blocked", ("blocked",))
    L += grp("Deferred", ("deferred",))
    L += grp("Rejected", ("rejected",))
    L += ["## Acceptance criteria", "", f"- PASS: {m['criteria_pass']} / {m['criteria_total']}",
          f"- REVIEWED only (LLM review, not verified): {m['criteria_reviewed_only']}", f"- FAIL: {m['criteria_fail']}",
          f"- NOT_RUN: {m['criteria_not_run']}", ""]
    checks = (verification or {}).get("checks", [])
    L += ["## Project checks", ""]
    if checks:
        L += ["| Check | Layer | Command | Status |", "|---|---|---|---|"]
        for c in checks:
            L.append(f"| {c['name']} | {c.get('layer', '-')} | `{c.get('command', '-')}` | {c['status']} |")
    else:
        L.append("_No project checks recorded (NOT_RUN)._")
    L += ["", "## Traceability", "", f"- Mapped to design: {m['mapped_to_design']} / {m['requirements_in_scope']}",
          f"- Mapped to tasks: {m['mapped_to_tasks']} / {m['requirements_in_scope']}",
          f"- With code evidence: {m['with_code_evidence']} / {m['requirements_in_scope']}",
          f"- Covered by automated tests: {m['covered_by_tests']} / {m['requirements_in_scope']}",
          f"- Orphan tasks: {', '.join(m['orphan_tasks']) or 'none'}", "",
          "_Statuses are derived from Harness Plans.md markers and recorded evidence. Unknown or not-run checks are never counted as passed._"]
    if st.get("blockers"):
        L += ["", "## Blockers", ""] + [f"- {b}" for b in st["blockers"]]
    return "\n".join(L) + "\n"
